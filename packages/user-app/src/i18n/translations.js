const dictionaries = {
  en: Object.fromEntries(entries.map(([az, en]) => [az, en])),
  ru: Object.fromEntries(entries.map(([az, , ru]) => [az, ru])),
};

export const translate = (source, language) => {
  if (language === "az") return source;
  const exact = dictionaries[language]?.[source];
  if (exact) return exact;

  const greeting = source.match(/^Salam, (.+)\. Zəhmət olmasa hesabınız üçün parol təyin edin\.$/);
  if (greeting) {
    return language === "en"
      ? `Hello, ${greeting[1]}. Please set a password for your account.`
      : `Здравствуйте, ${greeting[1]}. Пожалуйста, задайте пароль для своей учётной записи.`;
  }
  const addOption = source.match(/^Əlavə et: "(.+)"$/);
  if (addOption) {
    return language === "en" ? `Add: "${addOption[1]}"` : `Добавить: «${addOption[1]}»`;
  }
  const mapLevel = source.match(/^Səviyyə (\d+): (.+)$/);
  if (mapLevel) {
    return language === "en"
      ? `Level ${mapLevel[1]}: ${translate(mapLevel[2], language)}`
      : `Уровень ${mapLevel[1]}: ${translate(mapLevel[2], language)}`;
  }
  const uploaded = source.match(/^Yüklənmiş Fayllar \((\d+)\)$/);
  if (uploaded) return language === "en" ? `Uploaded files (${uploaded[1]})` : `Загруженные файлы (${uploaded[1]})`;

  const duration = source.match(/^(\d+) (?:s|saat) (\d+) dəq$/);
  if (duration) return language === "en" ? `${duration[1]} hr ${duration[2]} min` : `${duration[1]} ч ${duration[2]} мин`;
  const minutesSeconds = source.match(/^(\d+) dəq (\d+) san$/);
  if (minutesSeconds) return language === "en" ? `${minutesSeconds[1]} min ${minutesSeconds[2]} sec` : `${minutesSeconds[1]} мин ${minutesSeconds[2]} с`;
  const minutes = source.match(/^(\d+) dəq$/);
  if (minutes) return language === "en" ? `${minutes[1]} min` : `${minutes[1]} мин`;
  const times = source.match(/^(\d+) dəfə$/);
  if (times) return language === "en" ? `${times[1]} times` : `${times[1]} раз`;
  const days = source.match(/^(\d+) gün$/);
  if (days) return language === "en" ? `${days[1]} days` : `${days[1]} дн.`;
  const streak = source.match(/^Son (\d+) gündür ardıcıl oynama$/);
  if (streak) return language === "en" ? `Played ${streak[1]} days in a row` : `Серия игр: ${streak[1]} дн.`;
  const lastPlay = source.match(/^Axırıncı oyun: (.+)$/);
  if (lastPlay) return language === "en" ? `Last session: ${lastPlay[1]}` : `Последняя игра: ${lastPlay[1]}`;
  return source;
};
